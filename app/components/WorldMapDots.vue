interface Dot { x: number; y: number; phase: number }

const dots: Dot[] = []
map.forEach((row, y) => {
  for (let x = 0; x < row.length; x++) {
    if (row[x] === '1') {
      const i = dots.length
      // 确定性伪随机相位：每点独立明暗，形成此起彼伏的"万家灯火"效果
      const phase = (Math.sin(i * 127.1 + 311.7) * 0.5 + 0.5)
      dots.push({ x, y, phase })
    }
  }
})

const LOGICAL_W = 120
const LOGICAL_H = 43
const DOT_R = 0.32
const CYCLE = 5 // 闪烁周期（秒）

const canvasRef = ref<HTMLCanvasElement | null>(null)
let rafId = 0

// 单帧绘制：slice/cover 语义与 SVG preserveAspectRatio="xMidYMid slice" 一致
function drawFrame(ctx: CanvasRenderingContext2D, w: number, h: number, t: number) {
  ctx.clearRect(0, 0, w, h)
  ctx.fillStyle = '#fff'
  const scale = Math.max(w / LOGICAL_W, h / LOGICAL_H)
  const ox = (w - LOGICAL_W * scale) / 2
  const oy = (h - LOGICAL_H * scale) / 2
  for (const dot of dots) {
    const wave = 0.5 + 0.5 * Math.sin((2 * Math.PI) * (t / CYCLE + dot.phase))
    ctx.globalAlpha = 0.1 + 0.3 * wave // 0.1 ~ 0.4，压低亮度保证 Footer 内容可读性
    ctx.beginPath()
    ctx.arc(ox + (dot.x + 0.5) * scale, oy + (dot.y + 0.5) * scale, DOT_R * scale, 0, Math.PI * 2)
    ctx.fill()
  }
  ctx.globalAlpha = 1
}

onMounted(() => {
  const canvas = canvasRef.value
  if (!canvas) return
  const ctx = canvas.getContext('2d')
  if (!ctx) return

  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches
  const dpr = Math.min(window.devicePixelRatio || 1, 2) // 限制 dpr，避免高分屏开销过大

  // 按当前实际 CSS 尺寸同步位图尺寸（仅在尺寸变化时重置，避免清空画布）
  const syncCanvas = (): boolean => {
    const w = canvas.clientWidth
    const h = canvas.clientHeight
    if (w <= 0 || h <= 0) return false
    const bw = Math.max(1, Math.round(w * dpr))
    const bh = Math.max(1, Math.round(h * dpr))
    if (canvas.width !== bw || canvas.height !== bh) {
      canvas.width = bw
      canvas.height = bh
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
    }
    return true
  }

  // 无论是否减弱动效都持续跑 rAF：布局未完成时跳过绘制，
  // 布局一完成立即恢复显示，不会出现刷新后永久空白
  const loop = (now: number) => {
    const w = canvas.clientWidth
    const h = canvas.clientHeight
    if (w > 0 && h > 0) {
      syncCanvas()
      // 减弱动效时固定时间为 0：画面静止，仅保留各点相位明暗层次
      drawFrame(ctx, canvas.clientWidth, canvas.clientHeight, reduced ? 0 : now / 1000)
    }
    rafId = requestAnimationFrame(loop)
  }
  rafId = requestAnimationFrame(loop)
})

onBeforeUnmount(() => {
  if (rafId) cancelAnimationFrame(rafId)
})
